import { readFile, readdir } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDirectory = join(packageRoot, 'resources', 'css', 'src');
const outputDirectory = join(packageRoot, 'resources', 'dist');
const pluginFile = join(packageRoot, 'src', 'NoreviqThemePlugin.php');

const coreModules = [
    'foundation.css',
    'navigation.css',
    'components.css',
    'content.css',
    'overlays.css',
];

const bundles = [
    { output: 'noreviq.css', modules: coreModules },
    { output: 'noreviq-auth.css', modules: ['features/auth-noreviq.css'] },
    { output: 'presets/corners-sharp.css', modules: ['presets/corners-sharp.css'] },
    { output: 'presets/corners-subtle.css', modules: ['presets/corners-subtle.css'] },
    { output: 'presets/corners-native.css', modules: ['presets/corners-native.css'] },
    { output: 'presets/shadows-flat.css', modules: ['presets/shadows-flat.css'] },
    { output: 'presets/shadows-balanced.css', modules: ['presets/shadows-balanced.css'] },
    { output: 'presets/shadows-elevated.css', modules: ['presets/shadows-elevated.css'] },
];

const banner = (output) => `/*
 * Noreviq Filament Theme v1.0.0 — ${output}
 * Generated from resources/css/src by bin/build.mjs.
 * Do not edit this file directly.
 */`;

async function findCssFiles(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    const groups = await Promise.all(entries.map(async (entry) => {
        const path = join(directory, entry.name);

        return entry.isDirectory() ? findCssFiles(path) : [path];
    }));

    return groups.flat().filter((path) => path.endsWith('.css')).sort();
}

const sourcePaths = await findCssFiles(sourceDirectory);
const sources = await Promise.all(sourcePaths.map(async (path) => ({
    file: relative(sourceDirectory, path).replaceAll('\\', '/'),
    contents: await readFile(path, 'utf8'),
})));
const sourcesByFile = new Map(sources.map(({ file, contents }) => [file, contents]));
const plugin = await readFile(pluginFile, 'utf8');
const allCss = sources.map(({ contents }) => contents).join('\n');
const failures = [];

const declaredModules = bundles.flatMap(({ modules }) => modules).sort();
const discoveredModules = sources.map(({ file }) => file).sort();

if (JSON.stringify(declaredModules) !== JSON.stringify(discoveredModules)) {
    failures.push('Every source module must belong to exactly one declared bundle.');
}

for (const bundle of bundles) {
    const expected = `${banner(bundle.output)}\n\n${bundle.modules
        .map((file) => `/* module: ${file} */\n${sourcesByFile.get(file)?.trim() ?? ''}`)
        .join('\n\n')}\n`;
    const actual = await readFile(join(outputDirectory, bundle.output), 'utf8');

    if (actual !== expected) {
        failures.push(`${bundle.output} is stale. Run node bin/build.mjs.`);
    }
}

const previousApplicationName = ['volt', 'ara'].join('');

for (const forbidden of [previousApplicationName, '!important', '@apply', '@import', '@source']) {
    if (allCss.toLowerCase().includes(forbidden)) {
        failures.push(`Forbidden theme source found: ${forbidden}.`);
    }
}

if (/public function\s+(colors|primaryColor)\s*\(/.test(plugin)) {
    failures.push('The public API must not allow consumers to replace the Noreviq palette.');
}

const forbiddenPanelMethods = [
    'brandLogo',
    'brandName',
    'collapsedSidebarWidth',
    'darkMode',
    'defaultTheme',
    'favicon',
    'font',
    'maxContentWidth',
    'sidebarCollapsibleOnDesktop',
    'sidebarFullyCollapsibleOnDesktop',
    'sidebarWidth',
    'topNavigation',
];

for (const method of forbiddenPanelMethods) {
    if (new RegExp(`->${method}\\s*\\(`).test(plugin)) {
        failures.push(`The plugin changes host panel configuration: ${method}().`);
    }
}

for (const requiredMethod of ['corners', 'shadows', 'authStyle']) {
    if (!new RegExp(`public function ${requiredMethod}\\s*\\(`).test(plugin)) {
        failures.push(`Missing supported plugin option: ${requiredMethod}().`);
    }
}

for (const requiredOutput of ['noreviq.css', 'noreviq-auth.css']) {
    if (!plugin.includes(requiredOutput)) {
        failures.push(`The plugin does not register ${requiredOutput}.`);
    }
}

const forbiddenLayoutProperties = [
    'appearance', 'bottom', 'clear', 'clip', 'clip-path', 'contain', 'content',
    'cursor', 'display', 'flex', 'flex-basis', 'flex-direction', 'flex-flow',
    'flex-grow', 'flex-shrink', 'flex-wrap', 'float', 'gap', 'grid', 'grid-area',
    'grid-column', 'grid-row', 'height', 'inset', 'isolation', 'left', 'margin',
    'max-height', 'max-width', 'min-height', 'min-width', 'opacity', 'order',
    'overflow', 'padding', 'pointer-events', 'position', 'resize', 'right',
    'rotate', 'scale', 'scroll-behavior', 'top', 'touch-action', 'transform',
    'translate', 'user-select', 'visibility', 'white-space', 'width', 'z-index',
];

for (const property of forbiddenLayoutProperties) {
    const expression = new RegExp(`(^|[;{]\\s*)${property}\\s*:`, 'mi');

    if (expression.test(allCss)) {
        failures.push(`Theme CSS changes forbidden component behavior/layout: ${property}.`);
    }
}

if (/transition\s*:\s*[^;]*(\ball\b|\b(width|height|transform|position|margin|padding)\b)/i.test(allCss)) {
    failures.push('Transitions must be limited to paint-only properties.');
}

const nonPresetCss = sources
    .filter(({ file }) => !file.startsWith('presets/'))
    .map(({ contents }) => contents)
    .join('\n');

if (/border-radius\s*:\s*(0|[0-9.]+(?:px|rem|em))/i.test(nonPresetCss)) {
    failures.push('Component radius values must come from a corner preset token.');
}

if (allCss.includes('rgb(var(--noreviq-primary)')) {
    failures.push('Primary colors must follow Filament palette variables.');
}

for (const legacyColor of ['#6c5d80', '#9483ad', 'rgb(8 6 14']) {
    if (allCss.toLowerCase().includes(legacyColor)) {
        failures.push(`Legacy violet-tinted color remains: ${legacyColor}.`);
    }
}

const requiredStateSelectors = [
    '.fi-sidebar .fi-sidebar-item-btn .fi-sidebar-item-label',
    ':where(.fi-btn.fi-color-primary:not(.fi-outlined))',
    '.fi-fo-toggle-buttons input:checked + .fi-btn.fi-color-primary',
    '.fi-section:not(.fi-section-not-contained)',
    '.fi-sc-tabs.fi-contained',
    '.fi-btn:focus-visible',
    '.fi-toggle > :first-child',
    '.fi-fo-slider .noUi-connects',
    '.fi-sc-wizard-header-step-icon-ctn',
    '.fi-topbar .fi-logo',
    '@media print',
];

for (const selector of requiredStateSelectors) {
    if (!allCss.includes(selector)) {
        failures.push(`Missing component-state boundary: ${selector}.`);
    }
}

if (allCss.includes('.fi-fo-toggle-buttons-wrp')) {
    failures.push('The ToggleButtons field wrapper must not be painted as the control.');
}

if (/\.fi-tabs-item\s*,\s*\.fi-sc-tabs-tab/.test(allCss)) {
    failures.push('Tab panel containers must not be styled as tab buttons.');
}

for (const wrapper of ['.fi-account-widget', '.fi-wi-chart', '.fi-filament-info-widget']) {
    const escapedSelector = wrapper.replace('.', '\\.');

    if (new RegExp(`(^|,)\\s*${escapedSelector}\\s*(?=,|\\{)`, 'm').test(allCss)) {
        failures.push(`A widget grid wrapper must not be painted as a card: ${wrapper}.`);
    }
}

const hookNames = [...new Set(allCss.match(/\.fi-[a-z0-9-]+/g) ?? [])];

if (hookNames.length < 80 || hookNames.length > 280) {
    failures.push(`Expected 80–280 scoped Filament hooks, found ${hookNames.length}.`);
}

for (const bundle of bundles) {
    const css = await readFile(join(outputDirectory, bundle.output), 'utf8');
    let braces = 0;
    let parentheses = 0;
    let comment = false;
    let quote = null;
    let escaped = false;

    for (let index = 0; index < css.length; index += 1) {
        const character = css[index];
        const next = css[index + 1];

        if (comment) {
            if (character === '*' && next === '/') {
                comment = false;
                index += 1;
            }

            continue;
        }

        if (!quote && character === '/' && next === '*') {
            comment = true;
            index += 1;
            continue;
        }

        if (quote) {
            if (escaped) {
                escaped = false;
            } else if (character === '\\') {
                escaped = true;
            } else if (character === quote) {
                quote = null;
            }

            continue;
        }

        if (character === '"' || character === "'") {
            quote = character;
        } else if (character === '{') {
            braces += 1;
        } else if (character === '}') {
            braces -= 1;
        } else if (character === '(') {
            parentheses += 1;
        } else if (character === ')') {
            parentheses -= 1;
        }

        if (braces < 0 || parentheses < 0) {
            failures.push(`${bundle.output} is unbalanced near byte ${index}.`);
            break;
        }
    }

    if (comment || quote || braces || parentheses) {
        failures.push(`${bundle.output} has an unclosed CSS construct.`);
    }
}

if (failures.length) {
    console.error(failures.map((failure) => `- ${failure}`).join('\n'));
    process.exit(1);
}

console.log(`Verified ${bundles.length} assets, ${sources.length} modules, and ${hookNames.length} Filament hooks.`);
